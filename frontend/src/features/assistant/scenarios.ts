/**
 * Реестр сценариев помощника.
 *
 * Здесь лежит только то, что видит пользователь: заголовок карточки,
 * приветствие, список нужных данных и список того, что он получит в итоге.
 * Системные промпты для модели живут на бэкенде и подбираются по `id` —
 * см. docs/ai-scenarios.md.
 *
 * Добавить новый сценарий = дописать объект в этот массив. Экраны не меняются.
 */
export interface Scenario {
  id: ScenarioId;
  title: string;
  /** Короткая подпись для компактной кнопки на экране помощника. */
  shortTitle: string;
  icon: string;
  /** Одна строка на карточке в списке. */
  tagline: string;
  /** Первое сообщение помощника в диалоге. */
  greeting: string;
  /** Какие данные пользователь должен изложить. */
  needs: string[];
  /** Что он получит в ответе. */
  delivers: string[];
  placeholder: string;
}

