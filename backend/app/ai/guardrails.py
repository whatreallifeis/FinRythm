# Поиск источника в базе знаний по теме риска (ТЗ A4: для этих тем — 1 источник из базы).
KB_QUERIES = {
    "investment": "инвестиционные риски",
    "crypto": "криптовалюта финансовые пирамиды риски",
    "credit": "микрозаймы полная стоимость кредита",
    "gambling": "азартные игры ставки риски",
    "personal_data": "мошенничество коды из смс",
}

LIMITATIONS = [
    "Продукт не даёт инвестиционных рекомендаций, не совершает операций с деньгами "
    "и не принимает решение за вас.",
    "Секретные данные — пароли, коды, полные номера карт — сюда присылать не нужно.",
]


def classify_risky(message: str) -> str | None:
    """Категория рискованного запроса или None, если вопрос обычный."""
    text = message.casefold().replace("ё", "е")
    for intent, pattern in RULES:
        if pattern.search(text):
            return intent
    return None


def _source(intent: str, kb: KnowledgeSearch | None) -> SourceRef:
    if kb is not None and intent in KB_QUERIES:
        for item in kb.search(KB_QUERIES[intent], k=1):
            data: Any = item if isinstance(item, dict) else getattr(item, "__dict__", {})
            if data.get("url"):
                return SourceRef(title=data.get("source_title") or data["title"], url=data["url"])
    return EDUCATION_SOURCE


def refusal(intent: str, state: UserState, as_of: dt.date, kb: KnowledgeSearch | None = None) -> Explained:
    """Шаблонный отказ с объяснением и источником. Расчёты и LLM не вызываются."""
    return Explained(
        result={"text": TEXTS[intent]},
        sources=[_source(intent, kb)],
        limitations=LIMITATIONS,
        data_quality=DataQuality(sufficient=True, coverage_days=core_calls.coverage(state, as_of)),
    )
