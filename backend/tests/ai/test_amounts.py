from decimal import Decimal

import pytest
from app.ai.amounts import extract_amount


@pytest.mark.parametrize(
    ("text", "amount"),
    [
        ("Хочу купить наушники за 4900 ₽. Можно сегодня?", "4900"),
        ("можно потратить 3000?", "3000"),
        ("куплю кроссовки за 3 000", "3000"),
        ("Хватит ли на подарок за 3к?", "3000"),
        ("думаю про покупку за 2,5 тыс", "2500"),
        ("ноутбук за 14 900 ₽", "14900"),
        ("ноутбук за 14\u00a0900 ₽", "14900"),
        ("кофемашина 4900р", "4900"),
        ("билет 1 500,50 руб.", "1500.50"),
        ("до 5 октября хочу купить за 3000", "3000"),
        ("купить за 2000", "2000"),
        ("было 18 430 ₽, хочу потратить 3 000 ₽", "3000"),
        ("куртка за 7 тысяч", "7000"),
    ],
)
def test_extract_amount(text, amount):
    assert extract_amount(text) == Decimal(amount)


@pytest.mark.parametrize(
    "text",
    [
        "Можно сегодня что-нибудь купить?",
        "хватит ли денег до 10.10",
        "в 2027 году хочу купить ноутбук",
        "к 1 февраля 2027 куплю",
        "подожду 3 дня",
    ],
)
def test_no_amount(text):
    assert extract_amount(text) is None
